import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { cpus, totalmem, platform, release, tmpdir } from 'node:os';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { GameEngine } from '@rarity/game-core';
import { ImportService } from '../apps/server/dist/game/imports.js';

const MiB = 1024 ** 2, ceiling = 10 * MiB;
const cases = ['example', 'singapore', 'representative', 'ceiling-long', 'ceiling-dense', 'over-limit'];
const scenario = process.argv.find(x => x.startsWith('--scenario='))?.split('=')[1];
function generated(count, long) {
  return Buffer.from(JSON.stringify({ schemaVersion: 1, title: 'Synthetic capacity pack', tiers: [{ id: 't', name: 'Test', points: 100 }],
    prompts: Array.from({ length: 20 }, (_, round) => ({ id: 'r' + round, text: 'Synthetic round ' + round,
      answers: Array.from({ length: count }, (_, answer) => ({ text: 'Answer ' + answer, tierId: 't', aliases: long ? ['Alias ' + answer + ' ' + 'x'.repeat(long)] : [] })) })) }));
}
function input(name = scenario) {
  if (name === 'example' || name === 'singapore') return readFileSync(new URL('../examples/game.' + name + '.json', import.meta.url));
  if (name === 'representative') return generated(1800, 128);
  if (name === 'over-limit') return Buffer.alloc(ceiling + 1, 32);
  let low = 1, high = 12000;
  while (low < high) {
    const mid = Math.ceil((low + high) / 2);
    if (generated(mid, name === 'ceiling-long' ? 490 : 0).length <= ceiling) low = mid; else high = mid - 1;
  }
  const bytes = generated(low, name === 'ceiling-long' ? 490 : 0);
  return Buffer.concat([bytes, Buffer.alloc(ceiling - bytes.length, 32)]);
}
if (scenario) {
  assert(cases.includes(scenario));
  const inputFile = process.argv.find(x => x.startsWith('--input='))?.slice(8);
  const bytes = inputFile ? readFileSync(inputFile) : input();
  global.gc?.();
  const engine = new GameEngine({ now: () => performance.now(), newId: kind => kind + crypto.randomUUID(), newGameCode: () => '123456' });
  const service = new ImportService(engine);
  const started = performance.now(), cpu = process.cpuUsage();
  let outcome, detail;
  try { const result = await service.importBytes(bytes); outcome = 'STAGED'; detail = { prompts: result.summary.promptCount }; }
  catch (error) { outcome = error.code ?? 'UNEXPECTED'; detail = { message: error.message }; }
  const metrics = service.lastMetrics;
  await service.close(); global.gc?.();
  assert.equal(engine.state().phase, 'Setup');
  console.log(JSON.stringify({ scenario, bytes: bytes.length, inputSha256: createHash('sha256').update(bytes).digest('hex'), outcome, detail,
    wallMs: performance.now() - started, cpu: process.cpuUsage(cpu), metrics, afterClose: process.memoryUsage(), statePreserved: true }));
} else {
  const results = [];
  for (const name of cases) {
    const directory = mkdtempSync(tmpdir() + '/niche-import-');
    const path = directory + '/fixture.json';
    writeFileSync(path, input(name));
    const child = spawnSync(process.execPath, ['--expose-gc', fileURLToPath(import.meta.url), '--scenario=' + name, '--input=' + path], { encoding: 'utf8', timeout: 60000, maxBuffer: MiB });
    rmSync(directory, { recursive: true, force: true });
    assert.equal(child.status, 0, name + ': ' + child.stderr);
    const result = JSON.parse(child.stdout.trim()); results.push(result);
    console.log(name + ': ' + result.outcome + ', ' + result.bytes + ' bytes, ' + result.wallMs.toFixed(1) + ' ms');
  }
  assert(results.filter(r => r.scenario !== 'over-limit').every(r => r.outcome === 'STAGED'));
  assert.equal(results.at(-1).outcome, 'UPLOAD_TOO_LARGE');
  const report = { date: new Date().toISOString(), node: process.version, hardware: { cpu: cpus()[0]?.model, cores: cpus().length, memoryBytes: totalmem(), platform: platform(), kernel: release() },
    measurement: 'Each scenario in fresh process; 5ms RSS sampling includes parent+worker. Fixtures generated by separate parent, child only reads bytes; peak sampling may miss shorter spikes. afterClose measured after explicit GC, input buffer and engine still alive. CPU is microseconds. No browser/tunnel involved.', results };
  mkdirSync(new URL('../work/epic6/', import.meta.url), { recursive: true });
  writeFileSync(new URL('../work/epic6/import-capacity.json', import.meta.url), JSON.stringify(report, null, 2) + '\n');
}
